function category_department(?string $category, ?string $article = null): string {
    if ($article !== null && isset(X2POS_ARTICLE_OVERRIDES[$article])) {
        return X2POS_ARTICLE_OVERRIDES[$article][0];
    }
    return CATEGORY_HIERARCHY[$category ?? ''][0] ?? 'Без категории';
}

function category_subcategory(?string $category, ?string $article = null): string {
    if ($article !== null && isset(X2POS_ARTICLE_OVERRIDES[$article])) {
        return X2POS_ARTICLE_OVERRIDES[$article][1];
    }
    return CATEGORY_HIERARCHY[$category ?? ''][1] ?? 'Без категории';
}

// Детская/взрослая аудитория — не приходит из X2POS отдельным полем, но
// определяется по названию (суффикс JR — почти все детские модели JOMA
// подписаны так, плюс KIDS/JUNIOR/ДЕТСК) и по размерам (двойная возрастная
// нотация "N (LETTER)" — она физически не может быть у взрослой вещи).
// Проверено на реальном каталоге: находит 98/539 детских товаров, включая
// категории, которые в X2POS выглядят "взрослыми" по имени, но там сплошь
// JR-модели (напр. "сороконожки" — 100% детские).
function is_kids_product(string $name, array $sizes = []): bool {
    if (preg_match('/\bJR\b|KIDS|JUNIOR|ДЕТСК/ui', $name)) {
        return true;
    }
    foreach ($sizes as $size) {
        if (preg_match('/^\d+\s*\(/u', trim((string) $size))) {
            return true;
        }
    }
    return false;
}

// [article => bool] для всего каталога — считать один раз на отчёт, а не
// перезапрашивать sizes на каждую строку.
function compute_kids_map(PDO $pdo): array {
    $sizesByArticle = [];
    foreach ($pdo->query('SELECT article, size FROM stock') as $r) {
        $sizesByArticle[$r['article']][] = $r['size'];
    }

    $map = [];
    foreach ($pdo->query('SELECT article, name FROM products') as $r) {
        $map[$r['article']] = is_kids_product((string) $r['name'], $sizesByArticle[$r['article']] ?? []);
    }
    return $map;
}
